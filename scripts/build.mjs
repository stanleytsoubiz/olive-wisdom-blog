/**
 * build.mjs — build wrapper: prepare → build → restore.
 *
 * The cover optimisation (scripts/optimize-covers-build.mjs) rewrites
 * /images/covers/*.jpg → *.webp in two files the build consumes:
 *   - src/data/posts-generated.json — regenerated from frontmatter on
 *     every build, so rewriting it is harmless, and
 *   - public/data/images.json — TRACKED in git, so it must be restored.
 *
 * This wrapper guarantees prepare → build → restore always happens, even
 * when the build fails: the restore runs in a `finally` block. The working
 * tree is therefore never left dirty by a build.
 *
 *   node scripts/build.mjs static   # npm run build:  next build + pagefind
 *   node scripts/build.mjs server   # OpenNext buildCommand only: posts-data
 *                                   #   + covers + `next build` with
 *                                   #   OW_BUILD_TARGET=cf (server output).
 *                                   #   Never call this directly to deploy.
 *   node scripts/build.mjs cf       # npm run build:cf: opennextjs-cloudflare
 *                                   #   build (which runs the `server` mode
 *                                   #   above via open-next.config.ts
 *                                   #   buildCommand) + pagefind-opennext
 *
 * If the process itself is killed mid-build (SIGKILL, machine crash), the
 * finally block cannot run and images.json may be left with .webp refs.
 * That state is harmless: the next build rewrites it again (the prepare
 * step normalises stale .webp refs back to .jpg sources), and
 * `git checkout -- public/data/images.json` restores it by hand.
 */

import { spawnSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(__dirname, '..');

// Files the prepare step rewrites that must be restored afterwards.
// posts-generated.json is regenerated by build-posts-data.mjs at the start
// of every build, so restoring it is equally safe (and keeps git clean —
// the file is tracked).
const RESTORE_FILES = [
  path.join(projectRoot, 'public', 'data', 'images.json'),
  path.join(projectRoot, 'src', 'data', 'posts-generated.json'),
];

function run(label, command, args) {
  console.log(`[build] ── ${label}: ${command} ${args.join(' ')}`);
  const result = spawnSync(command, args, {
    cwd: projectRoot,
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  if (result.error) {
    // Throw (never process.exit here): main()'s finally block must run
    // first to restore images.json / posts-generated.json.
    const err = new Error(`could not start ${label}: ${result.error.message}`);
    err.exitCode = 1;
    throw err;
  }
  if (result.status !== 0) {
    const err = new Error(`${label} exited with code ${result.status}`);
    err.exitCode = result.status;
    throw err;
  }
}

function main() {
  const mode = process.argv[2] || 'static';
  if (mode !== 'static' && mode !== 'cf' && mode !== 'server') {
    console.error('[build] Usage: node scripts/build.mjs <static|cf|server>');
    process.exit(1);
  }

  // Back up the files the prepare step will rewrite, into a temp dir
  // (outside the repo, so no stray files ever land in the tree).
  const backupDir = fs.mkdtempSync(path.join(os.tmpdir(), 'olive-wisdom-build-'));
  const backups = new Map();
  for (const file of RESTORE_FILES) {
    if (fs.existsSync(file)) {
      const backup = path.join(backupDir, path.basename(file));
      fs.copyFileSync(file, backup);
      backups.set(file, backup);
    }
  }

  let exitCode = 0;
  try {
    if (mode === 'server') {
      // Invoked by OpenNext as its buildCommand (open-next.config.ts).
      // OW_BUILD_TARGET=cf makes next.config.js produce the server
      // build; spawnSync children inherit process.env, so setting it
      // here is enough. The prepare steps run here (not in `cf` mode)
      // so they execute exactly once per OpenNext build.
      process.env.OW_BUILD_TARGET = 'cf';
      run('build-posts-data', process.execPath, ['scripts/build-posts-data.mjs']);
      run('optimize-covers', process.execPath, ['scripts/optimize-covers-build.mjs']);
      run('next build (server)', 'npx', ['next', 'build']);
    } else if (mode === 'static') {
      run('build-posts-data', process.execPath, ['scripts/build-posts-data.mjs']);
      run('optimize-covers', process.execPath, ['scripts/optimize-covers-build.mjs']);
      run('next build', 'npx', ['next', 'build']);
      run('pagefind', 'npx', ['pagefind', '--site', 'out', '--output-path', 'out/pagefind']);
    } else {
      // cf: OpenNext runs the prepare steps + server build itself via
      // buildCommand; afterwards the search index is rebuilt against
      // the prerendered server HTML (no out/ exists in this pipeline).
      run('opennextjs-cloudflare build', 'npx', ['opennextjs-cloudflare', 'build']);
      run('pagefind-opennext', process.execPath, ['scripts/pagefind-opennext.mjs']);
    }
  } catch (err) {
    console.error('[build] ERROR:', err.message);
    exitCode = err.exitCode || 1;
  } finally {
    for (const [file, backup] of backups) {
      fs.copyFileSync(backup, file);
      console.log(`[build] restored ${path.relative(projectRoot, file)}`);
    }
    fs.rmSync(backupDir, { recursive: true, force: true });
  }
  process.exit(exitCode);
}

main();
